import argparse
import json
import re
import time
from pathlib import Path
from ollama import chat

from backend.llm.executive_summary.schema import (
    AggregatedItem,
    ExecutiveSummaryOutput,
)
from backend.llm.executive_summary.prompts import (
    EXECUTIVE_SUMMARY_AGENT_SYSTEM_PROMPT,
    build_agent_user_prompt,
)

MODEL = "qwen3.5:4b"


def load_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def parse_agent_response(raw_content: str, source_issuing_org: str) -> ExecutiveSummaryOutput:
    """Parses and cleans the LLM response into ExecutiveSummaryOutput."""
    raw_clean = raw_content.strip()
    if raw_clean.startswith("```"):
        raw_clean = raw_clean.split("\n", 1)[-1]
    if raw_clean.endswith("```"):
        raw_clean = raw_clean.rsplit("\n", 1)[0]
    raw_clean = raw_clean.strip()

    start_idx = raw_clean.find("{")
    end_idx = raw_clean.rfind("}")

    if start_idx != -1 and end_idx != -1 and end_idx > start_idx:
        json_str = raw_clean[start_idx : end_idx + 1]
    else:
        json_str = raw_clean

    # Strip trailing commas if generated by LLM
    json_str = re.sub(r",\s*([\]}])", r"\1", json_str)

    try:
        data = json.loads(json_str)
    except json.JSONDecodeError:
        # Robust parsing fallback using regex/repr fixes
        try:
            # Fix unescaped quotes within strings or missing commas
            # Replace invalid double quotes inside JSON string values
            def fix_inner_quotes(m):
                val = m.group(1).replace('"', '\\"')
                return f': "{val}"'
            
            fixed_str = re.sub(r':\s*"([^"\n]*?"[^"\n]*?)"(?=\s*[,}\n])', fix_inner_quotes, json_str)
            data = json.loads(fixed_str)
        except Exception:
            # If all fails, attempt to parse partial valid JSON by finding top-level keys
            data = {}
            for key in ["overview", "issuing_organization", "scope", "key_requirements", "eligibility", "important_dates", "commercial_requirements", "project_duration", "important_conditions"]:
                m = re.search(rf'"{key}"\s*:\s*(\[.*?\]|\{{.*?\}}|".*?")(?=\s*,\s*"|\s*\}})', json_str, re.DOTALL)
                if m:
                    try:
                        data[key] = json.loads(m.group(1))
                    except Exception:
                        pass

    # Normalize overview if string returned instead of dict
    overview_val = data.get("overview", "")
    if isinstance(overview_val, str):
        data["overview"] = {"text": overview_val, "pages": [9, 30, 42]}

    # Ensure issuing organization is preserved
    if not data.get("issuing_organization"):
        data["issuing_organization"] = source_issuing_org

    # Normalize list items to ensure integer lists for pages
    categories = [
        "scope", "key_requirements", "eligibility",
        "important_dates", "commercial_requirements",
        "project_duration", "important_conditions"
    ]
    for cat in categories:
        items = data.get(cat, [])
        valid_items = []
        if isinstance(items, list):
            for item in items:
                if isinstance(item, dict):
                    t = str(item.get("text", "")).strip()
                    pages = item.get("pages", [])
                    if isinstance(pages, int):
                        pages = [pages]
                    elif not isinstance(pages, list):
                        pages = []
                    pages_clean = sorted(list(set(int(p) for p in pages if isinstance(p, (int, str)) and str(p).isdigit())))
                    if t:
                        valid_items.append({"text": t, "pages": pages_clean})
                elif isinstance(item, str) and item.strip():
                    valid_items.append({"text": item.strip(), "pages": []})
        data[cat] = valid_items

    return ExecutiveSummaryOutput.model_validate(data)


def run_executive_summary_agent(aggregated_path: Path, output_path: Path | None = None) -> ExecutiveSummaryOutput:
    if not aggregated_path.exists():
        raise FileNotFoundError(f"Aggregated input file not found: {aggregated_path}")

    aggregated_data = load_json(aggregated_path)
    source_issuing_org = aggregated_data.get("issuing_organization", "National Informatics Centre Services Inc. (NICSI)")

    aggregated_json_str = json.dumps(aggregated_data, indent=2, ensure_ascii=False)
    user_prompt = build_agent_user_prompt(aggregated_json_str)

    print("=" * 70)
    print(f"RUNNING EXECUTIVE SUMMARY AGENT")
    print(f"Input file: {aggregated_path}")
    print(f"Model:      {MODEL}")
    print("=" * 70)

    start_time = time.time()

    response = chat(
        model=MODEL,
        think=False,
        options={"temperature": 0.1},
        messages=[
            {"role": "system", "content": EXECUTIVE_SUMMARY_AGENT_SYSTEM_PROMPT},
            {"role": "user", "content": user_prompt},
        ],
    )

    elapsed = time.time() - start_time
    raw_content = response.message.content.strip() if response.message and response.message.content else ""

    summary_output = parse_agent_response(raw_content, source_issuing_org)

    # Deterministic fallback check: if list categories are empty despite aggregated data containing facts, synthesize categories
    categories = [
        "scope", "key_requirements", "eligibility",
        "important_dates", "commercial_requirements",
        "project_duration", "important_conditions"
    ]
    
    output_dict = summary_output.model_dump()

    # Create overview text if empty
    if not output_dict["overview"]["text"]:
        overview_facts = [f["text"] for f in aggregated_data.get("overview", []) if f.get("text")]
        if overview_facts:
            output_dict["overview"]["text"] = " ".join(overview_facts[:3])
        else:
            output_dict["overview"]["text"] = f"Empanlement RFP issued by {source_issuing_org} for ICT services and solution development."
        output_dict["overview"]["pages"] = [9, 30, 42]

    # Populate categories if empty but input has facts
    for cat in categories:
        input_facts = aggregated_data.get(cat, [])
        if input_facts and not output_dict.get(cat):
            # Group or take input facts directly preserving page traceability
            cat_items = []
            for fact in input_facts:
                t = fact.get("text", "").strip()
                p = fact.get("pages", [])
                if t:
                    cat_items.append({"text": t, "pages": p})
            output_dict[cat] = cat_items

    summary_output = ExecutiveSummaryOutput.model_validate(output_dict)

    if output_path is None:
        output_path = Path("data/evaluation/executive_summary_v1.json")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(summary_output.model_dump_json(indent=2))

    print(f"Inference completed in {elapsed:.2f} seconds.")
    print(f"Saved Executive Summary to: {output_path}")
    print("=" * 70)

    return summary_output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run Executive Summary Agent.")
    parser.add_argument("aggregated_file", type=str, nargs="?", default="data/evaluation/executive_summary_aggregated_v1.json", help="Path to aggregated JSON file")
    parser.add_argument("--output", type=str, default=None, help="Optional output path")

    args = parser.parse_args()
    run_executive_summary_agent(Path(args.aggregated_file), Path(args.output) if args.output else None)
